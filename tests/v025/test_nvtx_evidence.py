def test_cached_executables_are_counted_separately_from_atime_sidecars():
    """987 top-level files is 493 executables, not 987 executables."""
    obj = _obj()
    stage2 = obj["cache_provenance"]["stage2_effective_cache"]
    breakdown = stage2["top_level_breakdown"]
    assert stage2["top_level_files"] == 987
    assert breakdown["cached_executables"] == 493
    assert breakdown["atime_sidecars"] == 493
    assert breakdown["lockfiles"] == 1
    assert (breakdown["cached_executables"] + breakdown["atime_sidecars"]
            + breakdown["lockfiles"] + len(breakdown["other"])) == stage2["top_level_files"]


def test_the_inflated_executable_count_is_retracted_in_place():
    correction = (_obj()["cache_provenance"]["stage2_effective_cache"]
                  ["top_level_breakdown"]["correction"])
    assert "executable cache files" in correction
    assert "roughly half" in correction


def test_each_cache_directory_carries_an_immutable_content_addressed_manifest():
    for key in ("stage2_effective_cache", "stage1_dedicated_cache"):
        manifest = _obj()["cache_provenance"][key]["cache_manifest"]
        assert manifest["content_addressed"] is True
        assert len(manifest["manifest_sha256"]) == 64
        assert manifest["entries"] == len(manifest["records"])
        assert all(len(row["sha256"]) == 64 for row in manifest["records"])


def test_the_manifest_digest_is_reproducible_from_its_own_records():
    """A manifest whose digest cannot be recomputed is not evidence."""
    import hashlib
    manifest = _obj()["cache_provenance"]["stage2_effective_cache"]["cache_manifest"]
    joined = "\n".join(f"{row['sha256']}  {row['name']}" for row in manifest["records"])
    assert hashlib.sha256(joined.encode()).hexdigest() == manifest["manifest_sha256"]


def test_temporal_coincidence_is_not_reported_as_causation():
    window = _obj()["cache_provenance"]["stage2_files_modified_in_window"]
    assert "NOT_CAUSAL" in window
    assert "temporal coincidence" in window["NOT_CAUSAL"]
    assert "writes" not in window.get("label", "")


def test_the_modified_set_is_broken_down_because_half_of_it_is_reads():
    """454 of the 920 are -atime sidecars, which JAX touches on cache READS."""
    window = _obj()["cache_provenance"]["stage2_files_modified_in_window"]
    assert window["breakdown"]["atime"] > 0
    assert window["breakdown"]["atime"] + window["breakdown"]["cache"] > 0.9 * window["count"]


def test_no_key_in_the_object_calls_these_writes():
    import json as _json
    text = _json.dumps(_obj())
    assert "writes_in_window" not in text
