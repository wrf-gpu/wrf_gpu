"""The NVTX/cache evidence object must match the filesystem, not my recollection.

Manager review of `55df8bfe` found three factual errors in the hand-assembled
version of `nvtx_compile_evidence.json`, each contradicted by authoritative
filesystem evidence:

1. it tested the **deprecated** `jax_cache.DEFAULT_CACHE_DIR`
   (`<DATA_ROOT>/gpuwrf_jax_cache`) and concluded from that directory's absence
   that the warm-cache explanation was falsified. The canonical resolver in
   `compile_cache` points at `$HOME/.cache/gpuwrf/jit/<version-tag>`, which
   existed since Jul 23 and was written to during Stage 2;
2. it reported "2020 small-module entries / zero autotune files". It is 454
   top-level executable-cache files **plus** 1566 `.textproto` records inside
   `xla_gpu_per_fusion_autotune_cache_dir/` — the earlier search looked for files
   *named* `xla_gpu_per_fu*` when that is a **directory**;
3. it called 107,412 summary rows "ranges"; the instance total is 157,080.

The object is now generated by `build_nvtx_compile_evidence.py`, and these tests
hold it against the live filesystem so it cannot drift back.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
if str(REPO / "scripts" / "v025") not in sys.path:
    sys.path.insert(0, str(REPO / "scripts" / "v025"))

EVIDENCE = REPO / "proofs/v025/m0/nvtx_compile_evidence.json"
pytestmark = pytest.mark.skipif(not EVIDENCE.exists(), reason="evidence object not built")


def _obj() -> dict:
    return json.loads(EVIDENCE.read_text())


# --------------------------------------------------------------------------- #
# 1. the canonical resolver                                                    #
# --------------------------------------------------------------------------- #
def test_the_canonical_resolver_is_used_not_the_deprecated_alias():
    node = _obj()["cache_provenance"]["canonical_resolver"]
    assert node["resolver"].endswith("compile_cache._default_cache_dir")
    assert "/.cache/gpuwrf/jit/" in node["path"], (
        "the object is not pointing at the canonical cache location"
    )
    assert "<DATA_ROOT>/gpuwrf_jax_cache" not in node["path"]


def test_the_deprecated_alias_is_recorded_as_such():
    """The wrong path must stay visible with a note, not be quietly dropped."""
    node = _obj()["cache_provenance"]["canonical_resolver"].get("deprecated_alias")
    assert node, "the deprecated alias that caused the error is not recorded"
    assert "jax_cache" in node["symbol"]
    assert "says nothing" in node["note"]


def test_the_backend_tag_aliasing_trap_is_documented():
    """A CPU generator resolves a different tag than the GPU process it describes."""
    node = _obj()["cache_provenance"]["canonical_resolver"]
    local = node.get("resolved_locally_as")
    assert local, "the local-vs-target tag difference is not recorded"
    assert local["version_tag"] != node["version_tag"]
    assert "cuda_sm120" in node["version_tag"]


def test_the_effective_stage2_cache_exists_and_predates_stage2():
    cache = _obj()["cache_provenance"]["stage2_effective_cache"]
    assert cache["exists"] is True
    assert cache["top_level_breakdown"]["cached_executables"] > 0


def test_the_falsification_is_explicitly_withdrawn():
    node = _obj()["the_346s_vs_4.382s_question"]
    assert "WITHDRAWN" in node["retracted_falsification"]
    assert node["status"] == "UNRESOLVED"
    assert node["MUST_NOT_BE_EQUATED"] is True


# --------------------------------------------------------------------------- #
# 2. directory-aware counts                                                    #
# --------------------------------------------------------------------------- #
@pytest.mark.parametrize("which", ["stage1_dedicated_cache", "stage2_effective_cache"])
def test_counts_are_directory_aware(which):
    """Top-level executable entries and nested autotune records are separate."""
    cache = _obj()["cache_provenance"][which]
    if not cache.get("exists"):
        pytest.skip(f"{which} not on disk")
    assert "top_level_files" in cache
    assert "autotune_records" in cache
    assert cache["total_files"] >= (
        cache["top_level_files"] + cache["autotune_records"]
    )


def test_stage1_matches_the_independently_verified_split():
    """454 top-level + 1566 autotune textproto — not '2020 small-module entries'."""
    cache = _obj()["cache_provenance"]["stage1_dedicated_cache"]
    if not cache.get("exists"):
        pytest.skip("stage 1 cache not on disk")
    assert cache["top_level_breakdown"]["cached_executables"] == 454
    assert cache["autotune_records"] == 1566
    assert cache["autotune_are_textproto"] == 1566
    assert cache["total_files"] == 2020


def test_only_the_top_level_big_module_count_is_claimed_zero():
    """Nothing may be claimed about the hashed autotune records."""
    node = _obj()["the_346s_vs_4.382s_question"]["only_proven_zero"]
    assert "TOP-LEVEL" in node
    assert "autotune" in node.lower()
    for which in ("stage1_dedicated_cache", "stage2_effective_cache"):
        cache = _obj()["cache_provenance"][which]
        if cache.get("exists"):
            assert cache["top_level_entries_for_big_module"] == 0


def test_autotune_records_are_not_attributed_to_a_module():
    for which in ("stage1_dedicated_cache", "stage2_effective_cache"):
        cache = _obj()["cache_provenance"][which]
        if cache.get("exists"):
            assert "NOT ATTRIBUTED" in cache["autotune_attribution"]


